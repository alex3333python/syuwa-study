LessonStep _learn({
  required String id,
  required String title,
  required String school,
  required String easy,
}) {
  return LessonStep(
    id: id,
    type: LessonStepType.learn,
    title: title,
    explanationSchoolJa: school,
    explanationEasyJa: easy,
    explanationNative: _nativeText(easy),
  );
}

LessonStep _summary({
  required String id,
  required String school,
  required String easy,
}) {
  return LessonStep(
    id: id,
    type: LessonStepType.summary,
    title: 'まとめ',
    explanationSchoolJa: school,
    explanationEasyJa: easy,
    explanationNative: _nativeText(easy),
  );
}

Question _q({
  required int id,
  required String type,
  required String school,
  required String easy,
  required List<String> choices,
  required int correct,
  required String explanation,
  required List<String> vocabulary,
  required List<String> tags,
  String equationHint = '',
  String thinkingHint = '',
  String visualHint = '',
  String pictureDescription = '',
  String diagramType = '',
  Map<String, String> diagramData = const {},
}) {
  final supportHints = [
    if (equationHint.isNotEmpty) '式ヒント: $equationHint',
    if (thinkingHint.isNotEmpty) '考え方: $thinkingHint',
    if (visualHint.isNotEmpty) '図ヒント: $visualHint',
  ].join('\n');

  return Question(
    id: id,
    type: type,
    unitId: 'grade3_division',
    promptSchoolJa: school,
    promptEasyJa: supportHints.isEmpty ? easy : '$easy\n$supportHints',
    promptNative: _nativeText(
      supportHints.isEmpty ? easy : '$easy\n$supportHints',
    ),
    choices: choices,
    correctAnswer: correct,
    explanationEasyJa: explanation,
    explanationNative: _nativeText(explanation),
    tags: ['division', 'grade3', 'math', 'no_remainder', ...tags],
    equationHint: equationHint,
    thinkingHint: thinkingHint,
    visualHint: visualHint,
    pictureDescription: pictureDescription,
    diagramType: diagramType,
    diagramData: diagramData,
    vocabulary: vocabulary,
    grade: 3,
    subject: 'math',
    unit: 'division',
  );
}

Map<AppLanguage, String> _nativeText(String fallback) {
  return {
    AppLanguage.portuguese: '$fallback\nTODO: suporte em português',
    AppLanguage.tagalog: '$fallback\nTODO: suporta sa Tagalog',
    AppLanguage.vietnamese: '$fallback\nTODO: hỗ trợ tiếng Việt',
  };
}
